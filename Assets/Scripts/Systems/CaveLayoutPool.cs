        /// <summary>FNV-1a 32 — 문자열 해시(결정론, Random API 0건).</summary>
        private static uint Hash32(string s)
        {
            uint h = 2166136261u;
            for (int i = 0; i < s.Length; i++)
            {
                h ^= s[i];
                h *= 16777619u;
            }
            return h;
        }

        /// <summary>
        /// [157차 P-C0] 존별 결정론 레이아웃 선택 — floorIndex1Based는 1~5.
        /// 반환 false = 클래식 경로(빌더 FloorCellmaps[floorIndex] 사용 — 계약테스트 좌표 핀 보존).
        /// </summary>
        public static bool TrySelect(string territoryId, int floorIndex1Based, out string[] cells)
        {
            cells = null;
            if (territoryId == ClassicTerritory1 || territoryId == ClassicTerritory2) return false;
            if (floorIndex1Based < 1 || floorIndex1Based > 5) return false;

            uint seed = Hash32(territoryId);
            if (floorIndex1Based == 1)
            {
                uint v = seed % 5u;
                if (v == 0u) return false;   // 클래식 F1(승인 도면 보존)
                cells = EntrancePool[(int)(v - 1u)];
                return true;
            }

            // 2~5층 — 갱도/습지/대홀/유적 순서 셔플(LCG 스텝 — 결정론)
            int[] order = { 1, 2, 3, 4 };
            uint s = seed ^ 0x9E3779B9u;
            for (int i = order.Length - 1; i > 0; i--)
            {
                s = s * 1664525u + 1013904223u;
                int j = (int)(s % (uint)(i + 1));
                (order[i], order[j]) = (order[j], order[i]);
            }
            int theme = order[floorIndex1Based - 2];
            s = s * 1664525u + 1013904223u;
            int variant = (int)(s % 4u);   // 0..3 — 신규 4종만(S 마커 보유 맵 한정)
            cells = theme switch
            {
                1 => GalleryPool[variant],
                2 => WetPool[variant],
                3 => HallPool[variant],
                _ => VaultPool[variant],
            };
            return true;
        }

        /// <summary>테마 이름(디버그 로그용) — TrySelect order 배열과 동기화.</summary>
        internal static string ThemeName(int theme) => theme switch
        {
            0 => "입구형",
            1 => "갱도형",
            2 => "습지형",
            3 => "대홀형",
            _ => "유적형",
        };
    }
